"""
DeepSeek SSE protocol parser
---------------------------

DeepSeek's chat stream is NOT a plain text-delta stream.  It is a JSON-Patch
style stream over a `response` object, verified against a captured browser session (HAR)
and against the live API.

Observed frame types (verified against a captured browser session (HAR) 2026-10-01,
372 entries, 14x completion + 1x regenerate):
  `event: ready`            {"request_message_id":N,"response_message_id":M,"model_type":"default"}
  `event: update_session`   {"updated_at":...}   and full snapshots
  `event: update_file`      {"id":"file-...","status":"SUCCESS","file_name":...,
                             "signed_path":...,"token_usage":...,"is_image":...,
                             "audit_result":"pass","width":...,"height":...}
  `event: title`            {"content":"<auto-generated title>"}
  `event: close`            {"click_behavior":"none","auto_resume":false}

There is NO `[DONE]` sentinel — the stream ends at `event: close`.
Keepalive lines containing only `:` are heartbeats and carry no data.

Patch packets (data has "p" + "o" + "v")
----------------------------------------
  {"p":"response/fragments/-1/content","o":"APPEND","v":"text"}
  {"p":"response/fragments/-1/content","v":"text"}  (no "o" — observed mid-answer
      when the server switches SSE encodings; treat as APPEND, see _apply_patch)
  {"p":"response/fragments","o":"APPEND","v":[{"type":"RESPONSE","content":"391"}]}
  {"p":"response/fragments","v":[{...}]}  (no "o" — observed when the answer
      fragment is appended after a SEARCH fragment; treat as APPEND)
  {"p":"response/fragments","o":"SET","v":[ ...whole array replaced... ]}
  {"p":"response","o":"BATCH","v":[{"p":"accumulated_token_usage","v":72},
                                  {"p":"quasi_status","v":"FINISHED"}]}
  {"p":"response/status","o":"SET","v":"FINISHED"}
  {"p":"response/conversation_mode","v":"SEARCH"}  (no "o" — mode switch when
      web search engages; DEFAULT otherwise)

Bare delta packets (data has only "v", a string)
------------------------------------------------
  {"v":" text"}  — a continuation of the previous APPEND

The critical detail
-------------------
A path of `response/fragments/-1/content` means "the LAST element of the
fragments array".  With thinking enabled the stream is:

  1. snapshot  -> fragments = [THINK:""]           (reasoning starts)
  2. APPEND    -> "We need to compute 17*23..."    (reasoning, into THINK)
  3. APPEND    -> fragments += [RESPONSE:"391"]     (the ANSWER)
  4. APPEND    -> "-1 is now the RESPONSE"           (answer continues)

A parser that just concatenates every `.../content` APPEND returns the
*reasoning* and silently throws the answer away.  This module tracks the
fragment list so callers get the right one.
"""

from __future__ import annotations

import json
import time

# Fragment types DeepSeek can emit
FRAG_THINK = "THINK"
FRAG_RESPONSE = "RESPONSE"
FRAG_SEARCH = "SEARCH"


class DeepSeekStreamParser:
    """
    Stateful parser for one DeepSeek SSE stream.

    Feed it raw SSE lines; read `.answer` for the RESPONSE text accumulated so
    far, `.reasoning` for the THINK text, `.searches` for citations, and
    `.status` / `.quasi_status` for stream state.

    `answer` is the important one: it deliberately excludes reasoning and
    search chatter, which is what an OpenAI-compatible client expects.
    """

    def __init__(self) -> None:
        self.fragments: list[dict] = []
        self.status: str | None = None
        self.quasi_status: str | None = None
        self.title: str | None = None
        self.request_message_id: int | None = None
        self.response_message_id: int | None = None
        self.model_type: str | None = None
        self.conversation_mode: str | None = None
        self.updated_at: float | None = None
        self.token_usage: int | None = None
        self.auto_resume: bool = False
        self.finished: bool = False
        self.searches: list[dict] = []
        self.files: list[dict] = []
        # DeepSeek reports upstream failures (rate limit, content filter, auth)
        # as an in-band frame rather than an HTTP status:
        #   {"type":"error","content":"…","finish_reason":"rate_limit_reached"}
        # A stream carrying only such a frame yields an empty answer, so this
        # is the only way a caller can tell "nothing to say" from "refused".
        self.upstream_error: str | None = None
        self.error_reason: str | None = None
        self.safe_message: str | None = None   # a diagnostic built here from numbers only; safe to show to the user
        self._event: str | None = None

    # ── Public views ───────────────────────────────────────────────────────────

    @property
    def answer(self) -> str:
        """Concatenated content of every RESPONSE fragment."""
        return "".join(f.get("content") or ""
                       for f in self.fragments
                       if f.get("type") == FRAG_RESPONSE)

    @property
    def reasoning(self) -> str:
        """Concatenated content of every THINK fragment."""
        return "".join(f.get("content") or ""
                       for f in self.fragments
                       if f.get("type") == FRAG_THINK)

    @property
    def has_content(self) -> bool:
        return any(f.get("type") == FRAG_RESPONSE for f in self.fragments)

    def citations(self) -> list[dict]:
        """Flatten SEARCH fragment references into citation records."""
        out: list[dict] = []
        for f in self.fragments:
            if f.get("type") != FRAG_SEARCH:
                continue
            for ref in (f.get("references") or f.get("results") or []):
                if isinstance(ref, dict):
                    out.append(ref)
        return out

    # ── Feeding ────────────────────────────────────────────────────────────────

    def feed_line(self, line: str) -> None:
        """Feed one raw SSE line. Lines that aren't `data:` are ignored —
        callers that care about `event:` names should read `.on_event`."""
        line = line.rstrip("\r\n")
        if not line or line == ":" or line.startswith(":"):
            return  # SSE keepalive heartbeat
        if line.startswith("event:"):
            self._event = line[6:].strip()
            return
        if line.startswith("{"):
            # DeepSeek refuses some requests with a bare JSON object instead of an SSE event
            # (for example a muted account: {"code":0,"data":{"biz_code":5,"biz_msg":"user is muted",...}}).
            try:
                bare = json.loads(line)
            except Exception:
                return
            if isinstance(bare, dict):
                self._envelope_error(bare)
            return
        if not line.startswith("data:"):
            return
        raw = line[5:].strip()
        if not raw or raw == "[DONE]":
            return
        try:
            obj = json.loads(raw)
        except Exception:
            return
        event, self._event = self._event, None
        if event and isinstance(obj, dict):
            self.on_event(event, obj)
        self._apply(obj)

    def _envelope_error(self, obj: dict) -> bool:
        """Recognise DeepSeek's ``{"data": {"biz_code": N, ...}}`` refusals. Only numbers become part of the message."""
        data = obj.get("data")
        if not isinstance(data, dict):
            return False
        biz = data.get("biz_code")
        if isinstance(biz, bool) or not isinstance(biz, int) or biz == 0:
            return False
        info = data.get("biz_data") if isinstance(data.get("biz_data"), dict) else {}
        if info.get("is_muted"):
            until = info.get("mute_until")
            when = ""
            if isinstance(until, (int, float)) and not isinstance(until, bool) and until > 0:
                when = " until " + time.strftime("%Y-%m-%d %H:%M UTC", time.gmtime(until))
            self.error_reason = "account_muted"
            self.safe_message = (f"DeepSeek has muted this account's chat{when} (biz_code {biz}). Waiting is the only fix; "
                                 "more requests will not lift it")
        else:
            self.error_reason = None
            self.safe_message = f"DeepSeek refused the request (biz_code {biz})"
        self.upstream_error = self.safe_message
        return True

    def on_event(self, event: str, data: dict) -> None:
        """Handle a named SSE event whose payload has already been decoded."""
        if event == "ready":
            self.request_message_id = data.get("request_message_id")
            self.response_message_id = data.get("response_message_id")
            self.model_type = data.get("model_type")
        elif event == "title":
            self.title = data.get("content")
        elif event == "close":
            self.auto_resume = bool(data.get("auto_resume"))
            self.finished = True
        elif event == "update_file":
            if isinstance(data, dict) and data.get("id"):
                self.files = [f for f in self.files if f.get("id") != data.get("id")]
                self.files.append(data)
                if data.get("token_usage") is not None:
                    try:
                        self.token_usage = int(data["token_usage"])
                    except (TypeError, ValueError):
                        pass
        elif event == "update_session":
            if isinstance(data.get("updated_at"), (int, float)):
                self.updated_at = data["updated_at"]

    def _apply(self, obj) -> None:
        if not isinstance(obj, dict):
            return
        if self._envelope_error(obj):
            return

        # In-band upstream error: {"type":"error","content":"…",
        # "finish_reason":"rate_limit_reached"}.  Capture it before any of the
        # event-shape sniffing below, which would otherwise discard it.
        if obj.get("type") == "error" or "error" in obj:
            detail = (obj.get("content") or obj.get("message")
                      or obj.get("error") or "")
            reason = obj.get("finish_reason")
            # Only this fixed diagnostic vocabulary may leave the provider.
            self.error_reason = reason if reason in ("rate_limit_reached", "content_filter", "authentication_error", "server_error") else None
            self.upstream_error = f"{detail} ({reason})" if reason else str(detail or "Upstream error")
            return

        # Named-event payloads also arrive on the generic data: channel.
        if "auto_resume" in obj:
            self.auto_resume = bool(obj.get("auto_resume"))
            self.finished = True
            return
        if "request_message_id" in obj and "response_message_id" in obj:
            self.request_message_id = obj.get("request_message_id")
            self.response_message_id = obj.get("response_message_id")
            if obj.get("model_type"):
                self.model_type = obj["model_type"]
            return
        # event: update_file — file parse status for attachments.  Carries
        # {id,status,file_name,signed_path,token_usage,is_image,audit_result,
        #  width,height}.  Tracked so callers can surface upload progress and
        #  token costs without a separate fetch_files poll.
        if "file_name" in obj and "status" in obj and "id" in obj:
            self.files = [f for f in self.files if f.get("id") != obj.get("id")]
            self.files.append(obj)
            if obj.get("token_usage") is not None:
                try:
                    self.token_usage = int(obj["token_usage"])
                except (TypeError, ValueError):
                    pass
            return
        if "content" in obj and "updated_at" not in obj and "p" not in obj:
            # `event: title` payload
            if isinstance(obj.get("content"), str) and len(obj) == 1:
                self.title = obj["content"]
                return
        if "updated_at" in obj and len(obj) == 1:
            self.updated_at = obj.get("updated_at")
            return

        # ── Full snapshot ─────────────────────────────────────────────────────
        v = obj.get("v")
        if isinstance(v, dict) and "response" in v:
            self._apply_snapshot(v["response"])
            return

        # ── Bare delta: continuation of the previous APPEND ───────────────────
        if isinstance(v, str) and "p" not in obj and "o" not in obj:
            self._append_to_last(v)
            return

        p = obj.get("p") or ""
        o = obj.get("o") or ""

        # ── Conversation-mode switch ────────────────────────────────────────
        # {"p":"response/conversation_mode","v":"SEARCH"} (no "o").  Emitted
        # when web search engages; DEFAULT otherwise.  Tracked for debugging
        # and for clients that render search state.
        if p == "response/conversation_mode" and isinstance(v, str):
            self.conversation_mode = v
            return

        if p == "response" and o in ("MERGE", "SET") and isinstance(v, dict):
            self._apply_snapshot(v)
            if self.status == "FINISHED":
                self.finished = True
            return

        if o == "BATCH":
            # Sub-patch paths are RELATIVE to the BATCH target path, e.g. a
            # BATCH on "response" carries {"p":"accumulated_token_usage"} and
            # {"p":"quasi_status"} — not "response/accumulated_token_usage".
            for patch in (v or []):
                if isinstance(patch, dict):
                    sub_p = patch.get("p") or ""
                    if not sub_p.startswith("response"):
                        sub_p = f"response/{sub_p}"
                    self._apply_patch(sub_p, patch.get("o") or "SET",
                                      patch.get("v"))
            return

        self._apply_patch(p, o, v)

    def _apply_snapshot(self, response: dict) -> None:
        frags = response.get("fragments")
        if isinstance(frags, list):
            self.fragments = [f for f in frags if isinstance(f, dict)]
        if response.get("status"):
            self.status = response["status"]
        if response.get("quasi_status"):
            self.quasi_status = response["quasi_status"]
        if response.get("conversation_mode"):
            self.conversation_mode = response["conversation_mode"]
        if response.get("accumulated_token_usage") is not None:
            self.token_usage = response["accumulated_token_usage"]
        for f in self.fragments:
            if f.get("type") == FRAG_SEARCH:
                self._collect_search(f)

    def _apply_patch(self, p: str, o: str, v) -> None:
        if p == "response/fragments/-1/content" and isinstance(v, str):
            # An operator-less content patch is a continuation APPEND — the
            # server emits {"p": ".../content", "v": "..."} with no "o" at
            # all when it switches SSE encodings mid-answer.  Treating the
            # missing operator as neither APPEND nor SET silently dropped
            # those characters, truncating replies mid-word.
            if o in ("APPEND", "", None):
                self._append_to_last(v)
            elif o == "SET":
                if self.fragments:
                    self.fragments[-1]["content"] = v
            return

        if p == "response/fragments":
            # Missing "o" with a list value is observed in the wild when the
            # answer fragment is appended after a SEARCH fragment:
            #   {"p":"response/fragments","v":[{RESPONSE,...}]}
            # Treat it as APPEND (keeps the SEARCH fragment for citations).
            # A true replacement always carries "o":"SET" explicitly.
            if o in ("APPEND", "", None) and isinstance(v, list):
                for f in v:
                    if isinstance(f, dict):
                        self.fragments.append(f)
                        if f.get("type") == FRAG_SEARCH:
                            self._collect_search(f)
            elif o == "SET" and isinstance(v, list):
                # Whole array replaced — e.g. reasoning is swapped out for the
                # answer once the model starts responding.
                self.fragments = [f for f in v if isinstance(f, dict)]
            return

        if p == "response/status" and isinstance(v, str):
            self.status = v
            if v == "FINISHED":
                self.finished = True
            return

        if p == "response/quasi_status" and isinstance(v, str):
            self.quasi_status = v
            if v == "FINISHED" and self.status is None:
                # BATCH reports quasi_status before the explicit status SET.
                self.finished = True
            return

        if p == "response/accumulated_token_usage":
            try:
                self.token_usage = int(v)
            except (TypeError, ValueError):
                pass
            return

        if p.startswith("response/fragments/-1/"):
            # elapsed_secs and friends — deliberately ignored
            return

        if p.startswith("response/") and o in ("SET", "APPEND"):
            return

    def _append_to_last(self, text: str) -> None:
        if not self.fragments:
            # Stream started mid-fragment; synthesise a RESPONSE fragment.
            self.fragments.append({"type": FRAG_RESPONSE, "content": ""})
        self.fragments[-1]["content"] = (self.fragments[-1].get("content") or "") + text

    def _collect_search(self, frag: dict) -> None:
        entry = {
            "status": frag.get("status"),
            "content": frag.get("content"),
            "queries": frag.get("queries") or [],
            "results": frag.get("results") or frag.get("references") or [],
        }
        if entry not in self.searches:
            self.searches.append(entry)


def parse_lines(lines: list[str]) -> DeepSeekStreamParser:
    """Parse a fully-collected list of SSE lines (non-streaming path)."""
    p = DeepSeekStreamParser()
    for ln in lines:
        p.feed_line(ln)
    return p
